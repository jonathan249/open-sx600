export function clampResistance(level: number): number {
  return Math.min(MAX_RESISTANCE, Math.max(MIN_RESISTANCE, Math.round(level)));
}

export function resistanceFrame(level: number): Uint8Array {
  return Uint8Array.from(RESISTANCE_TABLE[clampResistance(level)]);
}

/** Fallback data frame (15 bytes) when the bike exposes no FTMS service (L600–680). */
export function parseFitshowData(
  data: DataView,
): { resistance: number; cadence: number; power: number } | null {
  if (data.byteLength !== 15) return null;
  return {
    resistance: data.getUint8(5),
    cadence: data.getUint8(6),
    power: data.getUint16(9, true) / 10,
  };
}
