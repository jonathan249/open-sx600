/**
 * FitShow proprietary protocol used by the Sportstech SX600 console.
 *
 * Ported from QZ (qdomyos-zwift), GPL-3.0:
 * src/devices/fitplusbike/fitplusbike.cpp (sportstech_sx600 branches).
 *
 * Frame layout: 0x02, ...payload, checksum, 0x03
 * checksum = XOR of all payload bytes (verified against every frame below in tests).
 */

export const FITSHOW_SERVICE = 0xfff0;
export const FITSHOW_NOTIFY = 0xfff1;
export const FITSHOW_WRITE = 0xfff2;

export const MIN_RESISTANCE = 1;
export const MAX_RESISTANCE = 32;

export function checksum(payload: ArrayLike<number>): number {
  let x = 0;
  for (let i = 0; i < payload.length; i++) x ^= payload[i];
  return x;
}

export function frame(payload: number[]): Uint8Array {
  return Uint8Array.from([0x02, ...payload, checksum(payload), 0x03]);
}

